CREATE TABLE reserva (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT      NOT NULL REFERENCES usuario (id),
    mesa_id    BIGINT      NOT NULL REFERENCES mesa (id),
    fecha      DATE        NOT NULL,
    hora       TIME        NOT NULL,
    personas   INTEGER     NOT NULL CHECK (personas > 0),
    estado     VARCHAR(20) NOT NULL,
    CONSTRAINT ck_reserva_estado CHECK (estado IN ('CONFIRMADA', 'CANCELADA'))
);

CREATE INDEX ix_reserva_mesa_fecha ON reserva (mesa_id, fecha);
