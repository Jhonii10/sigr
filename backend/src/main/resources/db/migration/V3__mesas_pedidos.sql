CREATE TABLE mesa (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero    INTEGER     NOT NULL UNIQUE,
    capacidad INTEGER     NOT NULL CHECK (capacidad > 0),
    estado    VARCHAR(20) NOT NULL DEFAULT 'LIBRE',
    CONSTRAINT ck_mesa_estado CHECK (estado IN ('LIBRE', 'OCUPADA'))
);

CREATE TABLE pedido (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mesa_id   BIGINT         NOT NULL REFERENCES mesa (id),
    mesero_id BIGINT         NOT NULL REFERENCES usuario (id),
    estado    VARCHAR(20)    NOT NULL,
    total     NUMERIC(12, 2) NOT NULL DEFAULT 0,
    nota      VARCHAR(255),
    creado_en TIMESTAMP      NOT NULL,
    CONSTRAINT ck_pedido_estado CHECK (estado IN
        ('RECIBIDO', 'EN_PREPARACION', 'LISTO', 'ENTREGADO', 'PAGADO', 'CANCELADO'))
);

CREATE TABLE detalle_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT         NOT NULL REFERENCES pedido (id) ON DELETE CASCADE,
    plato_id        BIGINT         NOT NULL REFERENCES plato (id),
    cantidad        INTEGER        NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(12, 2) NOT NULL
);

CREATE INDEX ix_pedido_estado ON pedido (estado);
CREATE INDEX ix_detalle_pedido ON detalle_pedido (pedido_id);

