CREATE TABLE caja (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha          DATE           NOT NULL,
    monto_apertura NUMERIC(12, 2) NOT NULL,
    monto_cierre   NUMERIC(12, 2),
    usuario_id     BIGINT         NOT NULL REFERENCES usuario (id),
    estado         VARCHAR(20)    NOT NULL,
    abierta_en     TIMESTAMP      NOT NULL,
    cerrada_en     TIMESTAMP,
    CONSTRAINT ck_caja_estado CHECK (estado IN ('ABIERTA', 'CERRADA'))
);

CREATE TABLE pago (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id  BIGINT         NOT NULL UNIQUE REFERENCES pedido (id),
    caja_id    BIGINT         NOT NULL REFERENCES caja (id),
    medio_pago VARCHAR(20)    NOT NULL,
    valor      NUMERIC(12, 2) NOT NULL,
    creado_en  TIMESTAMP      NOT NULL,
    CONSTRAINT ck_pago_medio CHECK (medio_pago IN ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA'))
);

CREATE INDEX ix_pago_caja ON pago (caja_id);
